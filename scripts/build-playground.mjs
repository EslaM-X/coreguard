#!/usr/bin/env node
/**
 * build-playground.mjs — generate docs/playground/ from the REAL packages.
 *
 * What this is: the build step behind docs/PLAYGROUND.html. The page claims
 * "the engine you are driving is the real module" — a claim a rewrite would
 * rot — so the page never carries a re-authored engine. This script copies
 * the committed package sources byte-for-byte into docs/playground/ and
 * makes exactly three classes of mechanical edits, nothing else:
 *
 *   1. node:crypto imports      -> ./crypto-shim.js (a browser sha256/hmac
 *                                  with the same synchronous Node surface)
 *   2. package-relative imports -> sibling files inside docs/playground/
 *   3. the CLI entry guard      -> `typeof process !== "undefined"` first, so
 *                                  importing a module never evaluates
 *                                  `process` at load time in a browser (the
 *                                  tail stays dead code there, and still runs
 *                                  when the package itself is executed)
 *
 * Determinism: running it twice must produce the identical tree (the source
 * bytes pass through untouched; the generated header carries the engine's
 * provenance marker CG-ENGINE-PROVENANCE that the page contract checks).
 *
 * Usage:
 *   node scripts/build-playground.mjs
 *   node scripts/build-playground.mjs --check     # verify without writing
 *
 * Exit: 0 = written/verified, 1 = drifted under --check.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  console.error("usage: node scripts/build-playground.mjs [--check]");
  process.exit(2);
}

const OUT = join(root, "docs", "playground");

/** source file  -> output sibling name (relative imports rewrite to these) */
const MODULES = [
  ["packages/canonical/index.js", "canonical.js"],
  ["packages/canonical/uint.js", "uint-shim.js"],
  ["packages/budget/ledger.mjs", "ledger.js"],
  ["packages/acceptance/index.mjs", "acceptance.js"],
  ["packages/x402/index.mjs", "x402.js"],
  ["packages/job-integration/index.mjs", "job-integration.js"],
];

const CRYPTO_SHIM = join("packages", "crypto-shim-playground.js");
if (!checkOnly) console.log("BUILD-PLAYGROUND: (see docs/playground/README.md for the contract)");

/* ---------- provenance marker: the same bytes the page displays ---------- */

export const ENGINE_PROVENANCE_MARKER = "CG-ENGINE-PROVENANCE";

function rewriteImports(src) {
  return src
    // only the crypto import line changes identity
    .replace(/import \{([^}]*)\} from ["']node:crypto["'];?/g,
      (_m, names) => `import {${names}} from "./crypto-shim.js";`)
    // package-relative imports -> local siblings (flat engine dir)
    .replace(/(["'])\.\.\/(canonical|budget|acceptance|x402|job-integration)\/(index|ledger)?(\.mjs|\.js)?(["'])/g,
      (_m, q, pkg) => `${q}${pkgToSibling(pkg)}${q}`)
    .replace(/(["'])\.\/(index|uint)(\.js)?(["'])/g,
      (_m, _q, base) => base === "uint" ? `"./uint-shim.js"` : `"./canonical.js"`)
    // the packages' CLI tails run only when a file is executed directly; in a
    // browser module `process` does not exist, and a top-level ReferenceError
    // would abort the whole page's import — guard the entry, keep the tail
    .replace(/^if \(process\.argv\[1\]/gm, 'if (typeof process !== "undefined" && process.argv[1]');
}

function pkgToSibling(pkg) {
  // every package's entry module collapses to its flat engine name
  return pkg === "canonical" ? "./canonical.js"
    : pkg === "budget" ? "./ledger.js"
    : pkg === "acceptance" ? "./acceptance.js"
    : pkg === "x402" ? "./x402.js"
    : "./job-integration.js";
}

function header(sourcePath) {
  return [
    `/* ${ENGINE_PROVENANCE_MARKER}`,
    ` * generated by scripts/build-playground.mjs from ${sourcePath}`,
    ` * the real module bytes, rewritten ONLY in its import lines (see the generator's header).`,
    ` * regenerating: node scripts/build-playground.mjs`,
    ` */`,
  ].join("\n") + "\n";
}

/* ---------- build ---------- */

function main() {

  const written = new Map(); // output path -> bytes
  // crypto shim: only referenced through the crypto rewrite above
  const shimSource = readFileSync(join(root, CRYPTO_SHIM), "utf8");
  written.set("./crypto-shim.js", header("packages/crypto-shim-playground.js") + shimSource);

  for (const [src, out] of MODULES) {
    const raw = readFileSync(join(root, src), "utf8");
    written.set("./" + out, header(src) + rewriteImports(raw));
  }
  // a plain manifest the page and the contract can read without importing
  const manifest = JSON.stringify({
    generator: "scripts/build-playground.mjs",
    marker: ENGINE_PROVENANCE_MARKER,
    modules: Object.fromEntries([
      ...MODULES.map(([s, o]) => [o, s]),
      // the shim is written separately above, but a reader of the manifest must
      // still see where every engine file — shim included — comes from.
      ["crypto-shim.js", CRYPTO_SHIM.replace(/\\/g, "/")],
    ]),
    note: "every engine file is the real package bytes with import lines rewritten; nothing else",
  }, null, 2) + "\n";
  written.set("./manifest.json", manifest);

  if (checkOnly) {
    let drift = false;
    for (const [out, bytes] of written) {
      const target = join(OUT, out.replace("./", ""));
      let disk;
      try { disk = readFileSync(target, "utf8"); } catch { drift = true; console.error(`CHECK: MISSING ${out}`); continue; }
      if (disk !== bytes) {
        drift = true;
        const line = firstDiffLine(disk, bytes);
        console.error(`CHECK: DRIFT ${out} (first difference around line ${line}) — run: node scripts/build-playground.mjs`);
      }
    }
    if (drift) process.exit(1);
    console.log("BUILD-PLAYGROUND: engine is in sync with the packages (check)");
    return;
  }

  mkdirSync(OUT, { recursive: true });
  for (const out of readdirSync(OUT)) rmSync(join(OUT, out), { force: true });
  for (const [out, bytes] of written) {
    writeFileSync(join(OUT, out.replace("./", "")), bytes);
  }
  console.log(`BUILD-PLAYGROUND: wrote ${written.size} engine files into docs/playground/ from the real packages`);
}

function firstDiffLine(a, b) {
  const la = a.split("\n"), lb = b.split("\n");
  for (let i = 0; i < Math.max(la.length, lb.length); i++) if (la[i] !== lb[i]) return i + 1;
  return 0;
}

main();
